export async function initDatabaseSeed() {
  const productCount = await db.products.count();
  if (productCount === 0) {
    await db.products.bulkAdd(INITIAL_PRODUCTS);
  }
  const repairCount = await db.repairs.count();
  if (repairCount === 0) {
    await db.repairs.bulkAdd(INITIAL_REPAIRS);
  }
  const policeCount = await db.policeBook.count();
  if (policeCount === 0) {
    await db.policeBook.bulkAdd(INITIAL_POLICE_BOOK);
  }
  const customerCount = await db.customers.count();
  if (customerCount === 0) {
    await db.customers.bulkAdd(INITIAL_CUSTOMERS);
  }
  const supplierOrderCount = await db.supplierOrders.count();
  if (supplierOrderCount === 0) {
    await db.supplierOrders.bulkAdd(INITIAL_SUPPLIER_ORDERS);
  }
  const salesCount = await db.sales.count();
  if (salesCount === 0) {
    await db.sales.bulkAdd(INITIAL_SALES);
  }
  const closuresCount = await db.fiscalClosures.count();
  if (closuresCount === 0) {
    await db.fiscalClosures.bulkAdd(INITIAL_FISCAL_CLOSURES);
  }
}
